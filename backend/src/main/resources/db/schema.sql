-- ============================================================================
-- 排水管道结构缺陷普查评估平台 · PostgreSQL 18 schema
-- 设计要点：
--   1. 资产（井/管段）全部挂版本，观察归属按“检查发生时有效版本”固定
--   2. 新旧管段通过 app_segment_mapping 保留里程映射，历史缺陷不静默搬移
--   3. 观察先产生对齐候选，再固定归属；聚类后区分重复/冲突
--   4. 评估数据集只引用确认后的聚类，冲突位置暂停排序
-- 所有表使用 IF NOT EXISTS，可重复执行。
-- ============================================================================

-- ---------------------------------------------------------------- 账户与令牌
CREATE TABLE IF NOT EXISTS app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(64)  NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    display_name    VARCHAR(64)  NOT NULL,
    role            VARCHAR(16)  NOT NULL DEFAULT 'ENGINEER',
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT chk_user_role CHECK (role IN ('ENGINEER','ADMIN'))
);

CREATE TABLE IF NOT EXISTS app_login_token (
    token       VARCHAR(128) PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user(id),
    expires_at  TIMESTAMP NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- 资产版本域
CREATE TABLE IF NOT EXISTS app_asset_version (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no    VARCHAR(32)  NOT NULL UNIQUE,
    name          VARCHAR(128) NOT NULL,
    effective_at  TIMESTAMP    NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    note          TEXT,
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT chk_av_status CHECK (status IN ('DRAFT','ACTIVE','SUPERSEDED'))
);

CREATE TABLE IF NOT EXISTS app_manhole (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id    BIGINT NOT NULL REFERENCES app_asset_version(id),
    manhole_code  VARCHAR(32) NOT NULL,
    geom_x        NUMERIC(12,3),
    geom_y        NUMERIC(12,3),
    created_at    TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (version_id, manhole_code)
);

-- 管段：同一物理管段在不同版本中有不同行，parent_segment_id 指向上一版本行
CREATE TABLE IF NOT EXISTS app_pipe_segment (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id           BIGINT NOT NULL REFERENCES app_asset_version(id),
    segment_code         VARCHAR(32) NOT NULL,
    upstream_mh_id       BIGINT REFERENCES app_manhole(id),
    downstream_mh_id     BIGINT REFERENCES app_manhole(id),
    length_m             NUMERIC(10,3) NOT NULL,
    flow_direction       VARCHAR(16) NOT NULL,
    material             VARCHAR(32),
    diameter_mm          INTEGER,
    parent_segment_id    BIGINT REFERENCES app_pipe_segment(id),
    lifecycle_status     VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at           TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (version_id, segment_code),
    CONSTRAINT chk_ps_flow CHECK (flow_direction IN ('UP_TO_DOWN','DOWN_TO_UP')),
    CONSTRAINT chk_ps_lc   CHECK (lifecycle_status IN ('ACTIVE','SPLIT','MERGED','RETIRED'))
);

-- 新旧管段里程映射：坐标均为“沿管段走向、上游井为 0”的归一里程
CREATE TABLE IF NOT EXISTS app_segment_mapping (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_segment_id   BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    new_segment_id   BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    old_start_m      NUMERIC(10,3) NOT NULL,
    old_end_m        NUMERIC(10,3) NOT NULL,
    new_start_m      NUMERIC(10,3) NOT NULL,
    new_end_m        NUMERIC(10,3) NOT NULL,
    basis            VARCHAR(32) NOT NULL,
    note             TEXT,
    created_at       TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_sm_basis CHECK (basis IN ('STATION_EQUIVALENCE','SURVEY_MEASURE','AS_BUILT_CLIP'))
);

-- ---------------------------------------------------------------- 检测归档域
CREATE TABLE IF NOT EXISTS app_contractor_batch (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code           VARCHAR(64) NOT NULL UNIQUE,
    contractor           VARCHAR(128) NOT NULL,
    inspected_at         TIMESTAMP NOT NULL,
    grading_standard     VARCHAR(32) NOT NULL,
    direction_convention VARCHAR(64) NOT NULL,
    content_hash         VARCHAR(128),
    created_at           TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app_video (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT NOT NULL REFERENCES app_contractor_batch(id),
    video_code      VARCHAR(64) NOT NULL,
    file_uri        VARCHAR(255) NOT NULL,
    segment_hint    VARCHAR(32) NOT NULL,
    start_m         NUMERIC(10,3) NOT NULL,
    end_m           NUMERIC(10,3) NOT NULL,
    -- 视频里程方向：FORWARD 与管段归一里程同向；REVERSED 为反向里程（0 在下游井）
    station_direction VARCHAR(8) NOT NULL,
    content_hash    VARCHAR(128),
    duplicate_of_id BIGINT REFERENCES app_video(id),
    created_at      TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (batch_id, video_code),
    CONSTRAINT chk_v_dir CHECK (station_direction IN ('FORWARD','REVERSED'))
);

CREATE TABLE IF NOT EXISTS app_observation (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id          BIGINT NOT NULL REFERENCES app_video(id),
    batch_id          BIGINT NOT NULL REFERENCES app_contractor_batch(id),
    defect_type       VARCHAR(32) NOT NULL,
    raw_grade         VARCHAR(8) NOT NULL,
    station_start_m   NUMERIC(10,3) NOT NULL,
    station_end_m     NUMERIC(10,3) NOT NULL,
    evidence_uri      VARCHAR(255),
    evidence_strength VARCHAR(8) NOT NULL,
    status            VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    duplicate_of_id   BIGINT REFERENCES app_observation(id),
    cluster_id        BIGINT,
    created_at        TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_o_type CHECK (defect_type IN ('CRACK','DEFORMATION','LEAK','JOINT_DISLOCATION')),
    CONSTRAINT chk_o_ev   CHECK (evidence_strength IN ('FULL','PARTIAL','SPARSE')),
    CONSTRAINT chk_o_st   CHECK (status IN ('PENDING','CONFIRMED','DUPLICATE','QUARANTINED'))
);

-- ---------------------------------------------------------------- 等级标准与判读规则
