-- ============================================================================
-- 材料/年代队列统计域（cohort analytics）
-- 设计要点：
--   1. 资产沿革按区间保存投用/换管/内衬/材料变更，内衬/换管把服役年龄与材料
--      暴露时间从改造时点重新起算（同一物理管段形成多个暴露区间）
--   2. 检查历史只承认“有观察范围”的检测时段；遮挡区间单独标记，绝不计为无缺陷
--   3. 缺陷事件区分首次发现与修复后复发；复发关联原事件与原暴露区间，
--      不拆成两个独立管段重复统计
--   4. 资产沿革、检查暴露、缺陷事件、队列运行四类数据分别版本化：
--      补录/撤销只重算受影响队列，历史运行结果原样保留
-- ============================================================================

-- ---------------------------------------------------------------- 源数据版本
-- source_domain: ASSET_HISTORY 资产沿革 / INSPECTION_EXPOSURE 检查暴露 / DEFECT_EVENT 缺陷事件 / COHORT_RUN 队列运行
CREATE TABLE IF NOT EXISTS app_source_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_domain   VARCHAR(32) NOT NULL,
    version_no      VARCHAR(48) NOT NULL,
    source_note     TEXT,
    created_by      BIGINT REFERENCES app_user(id),
    created_at      TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (source_domain, version_no),
    CONSTRAINT chk_sv_domain CHECK (source_domain
        IN ('ASSET_HISTORY','INSPECTION_EXPOSURE','DEFECT_EVENT','COHORT_RUN'))
);

-- ---------------------------------------------------------------- 资产沿革（暴露区间）
-- event_type:
--   COMMISSION       投用（一个物理管段的首个区间起点）
--   PIPE_REPLACEMENT 换管（整段更换，新管段年龄从 0 起算）
--   RELINER          内衬改造（旧管结构保留，内衬层年龄从 0 起算；材料暴露时间分段）
--   MATERIAL_CHANGE  材料变更（仅材料口径变化，结构年龄延续）
--   RETIRE           退役（区间终点，之后不再产生暴露长度）
-- 每行是一个“服役/材料暴露区间”：[effective_from, effective_to)；
-- effective_to 为空表示持续至今。age_reset=true 时年龄从 effective_from 重新起算。
CREATE TABLE IF NOT EXISTS app_asset_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    physical_pipe_code  VARCHAR(32) NOT NULL,
    segment_code        VARCHAR(32) NOT NULL,
    event_type          VARCHAR(24) NOT NULL,
    material            VARCHAR(32) NOT NULL,
    diameter_mm         INTEGER NOT NULL,
    commission_year     INTEGER NOT NULL,
    length_m            NUMERIC(10,3) NOT NULL,
    effective_from      TIMESTAMP NOT NULL,
    effective_to        TIMESTAMP,
    age_reset           BOOLEAN NOT NULL DEFAULT false,
    source_version_id   BIGINT NOT NULL REFERENCES app_source_version(id),
    evidence_ref        VARCHAR(255),
    superseded_by_id   BIGINT REFERENCES app_asset_history(id),
    created_at          TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_ah_event CHECK (event_type
        IN ('COMMISSION','PIPE_REPLACEMENT','RELINER','MATERIAL_CHANGE','RETIRE'))
);
CREATE INDEX IF NOT EXISTS idx_ah_pipe ON app_asset_history(physical_pipe_code, effective_from);

-- ---------------------------------------------------------------- 检查暴露（有观察范围的检测时段）
-- coverage_status:
--   OBSERVED 有效观察范围（可作为缺陷/无缺陷判定的分母）
--   OBSCURED 检查被遮挡（泥浆/水位/障碍物等），不计无缺陷、不计入有效覆盖
-- 撤销观察时把行 status 置为 REVOKED 并登记撤销版本，重算时整行剔除但留痕。
CREATE TABLE IF NOT EXISTS app_inspection_exposure (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    physical_pipe_code  VARCHAR(32) NOT NULL,
    segment_code        VARCHAR(32) NOT NULL,
    batch_code          VARCHAR(64) NOT NULL,
    inspected_at        TIMESTAMP NOT NULL,
    station_start_m     NUMERIC(10,3) NOT NULL,
    station_end_m       NUMERIC(10,3) NOT NULL,
    coverage_status     VARCHAR(16) NOT NULL,
    obscured_reason     VARCHAR(128),
    risk_zone           VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    source_version_id   BIGINT NOT NULL REFERENCES app_source_version(id),
    status              VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    revoked_by_version_id BIGINT REFERENCES app_source_version(id),
    evidence_ref        VARCHAR(255),
    created_at          TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_ie_cov CHECK (coverage_status IN ('OBSERVED','OBSCURED')),
    CONSTRAINT chk_ie_risk CHECK (risk_zone IN ('HIGH_RISK','NORMAL')),
    CONSTRAINT chk_ie_status CHECK (status IN ('ACTIVE','REVOKED'))
);
CREATE INDEX IF NOT EXISTS idx_ie_pipe ON app_inspection_exposure(physical_pipe_code, inspected_at);

-- ---------------------------------------------------------------- 缺陷事件与维修
-- event_kind: FIRST_FINDING 首次发现 / RECURRENCE 修复后复发
-- 复发行 original_event_id 指向首次发现事件，并继承其暴露区间编号 exposure_key，
-- 统计时作为同一位置的新发事件计入复发率，而不是重复统计为两个独立管段。
-- 维修记录内嵌在本表（REPAIR_* 字段）：修复后同一区间再次发现即为复发。
CREATE TABLE IF NOT EXISTS app_defect_event (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    physical_pipe_code   VARCHAR(32) NOT NULL,
    segment_code         VARCHAR(32) NOT NULL,
    event_kind           VARCHAR(16) NOT NULL,
    original_event_id    BIGINT REFERENCES app_defect_event(id),
    defect_type          VARCHAR(32) NOT NULL,
    normalized_grade     INTEGER NOT NULL,
    station_start_m      NUMERIC(10,3) NOT NULL,
    station_end_m        NUMERIC(10,3) NOT NULL,
    found_at             TIMESTAMP NOT NULL,
    exposure_key         VARCHAR(64) NOT NULL,
    repair_id            VARCHAR(48),
    repaired_at          TIMESTAMP,
    repair_method        VARCHAR(64),
    post_repair_status   VARCHAR(24),
    source_version_id    BIGINT NOT NULL REFERENCES app_source_version(id),
    evidence_ref         VARCHAR(255),
    created_at           TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_de_kind CHECK (event_kind IN ('FIRST_FINDING','RECURRENCE')),
    CONSTRAINT chk_de_type CHECK (defect_type
        IN ('CRACK','DEFORMATION','LEAK','JOINT_DISLOCATION')),
    CONSTRAINT chk_de_grade CHECK (normalized_grade BETWEEN 1 AND 4),
    CONSTRAINT chk_de_prs CHECK (post_repair_status IS NULL OR post_repair_status
        IN ('REPAIRED_NO_DEFECT','REPAIRED_RECURRED','STILL_OPEN'))
);
CREATE INDEX IF NOT EXISTS idx_de_pipe ON app_defect_event(physical_pipe_code, found_at);

-- ---------------------------------------------------------------- 队列运行（版本化结果）
-- estimation_method:
--   NAIVE 年龄分层后直接比较已检查长度中的缺陷比例（透明，但高风险区过度检查会偏高）
--   IPW   按历史检查概率对样本逆概率加权（减轻选择性检查，要求选检特征可观测，需检查极端权重）
-- status: CURRENT 当前有效 / SUPERSEDED 被补录或撤销触发的重算取代 / ARCHIVED 手动归档
CREATE TABLE IF NOT EXISTS app_cohort_run (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_code           VARCHAR(64) NOT NULL UNIQUE,
    as_of_date         DATE NOT NULL,
    estimation_method  VARCHAR(16) NOT NULL,
    age_band_years     INTEGER NOT NULL,
    asset_version_id   BIGINT NOT NULL REFERENCES app_source_version(id),
    exposure_version_id BIGINT NOT NULL REFERENCES app_source_version(id),
    defect_version_id  BIGINT NOT NULL REFERENCES app_source_version(id),
    selection_model    TEXT,
    method_note        TEXT,
    non_inference_note TEXT,
    status             VARCHAR(16) NOT NULL DEFAULT 'CURRENT',
    superseded_run_id  BIGINT REFERENCES app_cohort_run(id),
    generated_by       BIGINT REFERENCES app_user(id),
    generated_at       TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_cr_method CHECK (estimation_method IN ('NAIVE','IPW')),
    CONSTRAINT chk_cr_status CHECK (status IN ('CURRENT','SUPERSEDED','ARCHIVED'))
);

-- ---------------------------------------------------------------- 队列结果行（年龄分层）
CREATE TABLE IF NOT EXISTS app_cohort_cell (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                 BIGINT NOT NULL REFERENCES app_cohort_run(id),
    material               VARCHAR(32) NOT NULL,
    commission_decade      VARCHAR(16) NOT NULL,
    diameter_band          VARCHAR(16) NOT NULL,
    age_band               VARCHAR(16) NOT NULL,
    -- 分母与长度口径（全部可追溯到来源行）
    total_length_m         NUMERIC(12,3) NOT NULL,
    inspected_length_m     NUMERIC(12,3) NOT NULL,
    obscured_length_m      NUMERIC(12,3) NOT NULL,
    effective_coverage     NUMERIC(6,4) NOT NULL,
    -- 缺陷与复发（事件数，复发不重复管段）
    defect_event_count     INTEGER NOT NULL,
    first_finding_count    INTEGER NOT NULL,
    recurrence_count       INTEGER NOT NULL,
    defective_length_m     NUMERIC(12,3) NOT NULL,
    defect_ratio           NUMERIC(8,6),
    recurrence_rate        NUMERIC(8,6),
    -- 加权口径
    weight_sum             NUMERIC(14,4),
    weighted_defect_length NUMERIC(14,4),
    weighted_inspected_length NUMERIC(14,4),
    weighted_defect_ratio  NUMERIC(8,6),
    min_weight             NUMERIC(10,4),
    max_weight             NUMERIC(10,4),
    -- 证据与可推断性
    evidence_sources       TEXT NOT NULL,
    low_coverage_flag      BOOLEAN NOT NULL DEFAULT false,
    extreme_weight_flag    BOOLEAN NOT NULL DEFAULT false,
    non_inferable_flag     BOOLEAN NOT NULL DEFAULT false,
    UNIQUE (run_id, material, commission_decade, diameter_band, age_band)
);
CREATE INDEX IF NOT EXISTS idx_cc_run ON app_cohort_cell(run_id);

-- 队列单元格证据明细：每个分母/事件都能下钻到来源行
CREATE TABLE IF NOT EXISTS app_cohort_evidence (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        BIGINT NOT NULL REFERENCES app_cohort_run(id),
    cell_key      VARCHAR(160) NOT NULL,
    evidence_kind VARCHAR(24) NOT NULL,
    source_ref    VARCHAR(128) NOT NULL,
